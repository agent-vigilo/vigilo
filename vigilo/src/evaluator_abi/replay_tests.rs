#[derive(Deserialize)]
struct Fixture {
    name: String,
    body: String,
    configuration: ResponseConfiguration,
    expected_sentiment: String,
}

fn input(mapped: MappedResponse) -> EvaluatorInput {
    let mut input: EvaluatorInput = serde_json::from_value(json!({
        "run_id":"run", "execution_id":"execution", "attempt_id":"attempt",
        "case":{"id":"case", "task_type":"classification", "input":{"text":"bad prompt must not be scored"}},
        "actual":{}, "evaluator_config":{}
    })).unwrap();
    input.actual.captured_body = Some(mapped.original.clone());
    input.actual.mapping = Some(Arc::new(Ok(mapped)));
    input
}

fn hash(bytes: &[u8]) -> String {
    blake3::hash(bytes).to_hex().to_string()
}

/// Compare representations, ordering, metadata and exact bytes, excluding live
/// handles which must be regenerated by each evaluator invocation.
fn observable(mapped: &MappedResponse) -> Value {
    use vigilo::response::OutputItem;
    let source = |source: &MappedSource| match source {
        MappedSource::InlineText { text } => json!({"inline":text}),
        MappedSource::BodyRange {
            offset,
            byte_length,
        } => {
            json!({"offset":offset,"length":byte_length,"bytes":&mapped.original.bytes()[*offset as usize..(*offset+*byte_length) as usize]})
        }
        MappedSource::Resource { body } => json!({"resource_bytes":body.bytes()}),
    };
    let part = |part: &vigilo::response::ContentPart<MappedSource>| json!({"media_type":part.media_type,"source":source(&part.source)});
    let items = mapped.items.as_ref().map(|items| items.iter().map(|item| match item {
        OutputItem::Message {id,role,content} => json!({"type":"message","id":id,"role":role,"content":content.iter().map(&part).collect::<Vec<_>>()}),
        OutputItem::ToolCall {call_id,name,arguments} => json!({"type":"tool_call","call_id":call_id,"name":name,"arguments":part(arguments)}),
        OutputItem::ToolResult {call_id,content,is_error} => json!({"type":"tool_result","call_id":call_id,"content":content.iter().map(&part).collect::<Vec<_>>(),"is_error":is_error}),
    }).collect::<Vec<_>>());
    json!({"original":mapped.original.bytes(),"content_type":mapped.original.content_type(),"items":items,"status":mapped.status,"stop_reason":mapped.stop_reason})
}

#[test]
fn retained_provider_shapes_reproduce_mapped_inputs_and_wasm_scores() {
    let wasm = fs::read(
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../target/wasm32-wasip2/release/sentiment_basic_en.wasm"),
    )
    .unwrap();
    let runtime = Wasm::new(Config {
        timeout_ms: 0,
        ..Default::default()
    })
    .unwrap();
    let evaluator = PreparedEvaluator::compile(&runtime, &wasm, &current_identity()).unwrap();
    let mut digest = blake3::Hasher::new();
    digest
        .update_reader(fs::File::open(std::env::current_exe().unwrap()).unwrap())
        .unwrap();
    let runtime_digest = digest.finalize().to_hex().to_string();
    let mut compatibility = std::collections::hash_map::DefaultHasher::new();
    runtime
        .engine()
        .precompile_compatibility_hash()
        .hash(&mut compatibility);
    let fingerprint = format!("{:x}-{}", compatibility.finish(), std::env::consts::ARCH);
    let evaluator_digest = hash(&wasm);
    let plan = EvaluatorExecutionPlan::new(
        hash(b"frozen scoring policy"),
        vec![ResolvedEvaluator {
            evaluator_ref: "vigilo/sentiment-basic-en:0.1.0".into(),
            evaluator_id: Uuid::nil(),
            content_hash: evaluator_digest.clone(),
            abi: current_identity(),
            runtime: "wasmtime".into(),
            runtime_version: env!("VIGILO_WASMTIME_VERSION").into(),
            runtime_fingerprint: fingerprint,
        }],
    );
    let available: BTreeSet<_> = [runtime_digest.clone(), evaluator_digest]
        .into_iter()
        .collect();
    let fixtures: Vec<Fixture> =
        serde_json::from_str(include_str!("fixtures/response-replay.json")).unwrap();
    for fixture in fixtures {
        let body = CapturedBody::new(fixture.body.into_bytes(), Some("application/json".into()));
        let mapped = map_response(&body, Some(&fixture.configuration), Default::default()).unwrap();
        let expected_input = observable(&mapped);
        let first = evaluator.execute(&runtime, input(mapped.clone())).unwrap();
        assert!(
            matches!(&first.outcome,EvaluatorOutcome::Completed(Measurement::Ordinal {value}) if value == &fixture.expected_sentiment),
            "{}",
            fixture.name
        );
        let packet = RetainedResponse::capture(
            Provenance {
                run_id: Uuid::nil(),
                execution_id: Uuid::nil(),
                attempt_id: Uuid::nil(),
                case_hash: hash(b"frozen case"),
                profile_hash: hash(&serde_json::to_vec(&fixture.configuration).unwrap()),
                execution_plan_hash: plan.hash().unwrap(),
                runtime_artifact_digest: runtime_digest.clone(),
                external_dependencies: ExternalDependencies::None,
            },
            PersistenceMode::Full,
            Some(&body),
            Some(&fixture.configuration),
            Some(Ok(&mapped)),
        )
        .unwrap();
        // Drop live mapping/body ownership. Only serialized storage values survive.
        let metadata = serde_json::to_vec(&packet.metadata_json().unwrap()).unwrap();
        let payload = packet.payload().to_vec();
        drop((packet, mapped, body));
        let retained =
            RetainedResponse::from_storage(serde_json::from_slice(&metadata).unwrap(), payload)
                .unwrap();
        assert!(
            retained
                .missing_dependencies(&plan, &available)
                .unwrap()
                .is_empty()
        );
        assert_eq!(
            retained
                .missing_dependencies(&plan, &BTreeSet::new())
                .unwrap()
                .len(),
            2
        );
        let restored = retained.reconstruct().unwrap();
        assert_eq!(observable(&restored), expected_input, "{}", fixture.name);
        let replayed = evaluator.execute(&runtime, input(restored)).unwrap();
        assert_eq!(
            serde_json::to_value(&first.outcome).unwrap(),
            serde_json::to_value(&replayed.outcome).unwrap(),
            "{}",
            fixture.name
        );
        let mut wrong_plan = plan.clone();
        wrong_plan.evaluators[0].content_hash = hash(b"different artifact");
        assert!(
            retained
                .missing_dependencies(&wrong_plan, &available)
                .is_err()
        );
    }
}

#[test]
fn replay_binds_fresh_handles_and_rejects_the_previous_invocations_handle() {
    let bytes = fs::read(
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../target/wasm32-wasip2/release/response_resource_fixture.wasm"),
    )
    .unwrap();
    let runtime = Wasm::new(Config {
        timeout_ms: 0,
        ..Default::default()
    })
    .unwrap();
    let evaluator = PreparedEvaluator::compile(&runtime, &bytes, &current_identity()).unwrap();
    let body = CapturedBody::new(
        vec![0, 255, 42, 10],
        Some("application/octet-stream".into()),
    );
    let mapping = map_response(&body, None, Default::default()).unwrap();
    let first = evaluator.execute(&runtime, input(mapping.clone())).unwrap();
    let old_handle = first.metadata.as_u64().unwrap();
    let packet = RetainedResponse::capture(
        Provenance {
            run_id: Uuid::nil(),
            execution_id: Uuid::nil(),
            attempt_id: Uuid::nil(),
            case_hash: hash(b"case"),
            profile_hash: hash(b"profile"),
            execution_plan_hash: EvaluatorExecutionPlan::new(hash(b"policy"), vec![])
                .hash()
                .unwrap(),
            runtime_artifact_digest: hash(b"fixture runtime"),
            external_dependencies: ExternalDependencies::None,
        },
        PersistenceMode::Full,
        Some(&body),
        None,
        Some(Ok(&mapping)),
    )
    .unwrap();
    let stored =
        RetainedResponse::from_storage(packet.metadata_json().unwrap(), packet.payload().to_vec())
            .unwrap();
    let mut replay = input(stored.reconstruct().unwrap());
    // The real Wasm fixture attempts to read this old handle and requires denial.
    replay.evaluator_config = json!(old_handle);
    let second = evaluator.execute(&runtime, replay).unwrap();
    assert_ne!(second.metadata.as_u64().unwrap(), old_handle);
    assert!(matches!(
        second.outcome,
        EvaluatorOutcome::Completed(Measurement::Binary { value: true })
    ));
}
